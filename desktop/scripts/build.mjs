#!/usr/bin/env node
/**
 * Bundle desktop/src/plugin.jsx → desktop/plugin.js.
 * Host-provided externals: @hermes/plugin-sdk, react, react/jsx-runtime.
 * Everything else (@a2ui/*, zod, markdown-it) is inlined.
 */
import * as esbuild from 'esbuild'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const desktopDir = resolve(here, '..')
const pluginRoot = resolve(desktopDir, '..')
const outfile = resolve(pluginRoot, 'desktop/plugin.js')
const check = process.argv.includes('--check')

const banner = `/* uirizz desktop bundle. Generated by desktop/scripts/build.mjs. Do not edit by hand. */
import * as __uirizzReact from "react";
import * as __uirizzJsxRuntime from "react/jsx-runtime";
var require = function __uirizzRequire(name) {
  var mod = name === "react" ? __uirizzReact
    : name === "react/jsx-runtime" || name === "react/jsx-dev-runtime" ? __uirizzJsxRuntime
    : null;
  if (!mod) throw new Error("cannot require " + name);
  var d = mod.default;
  if (d && (d.createElement || d.useState || d.jsx || typeof d === "function")) return d;
  return mod;
};
`

const options = {
  absWorkingDir: desktopDir,
  entryPoints: ['src/plugin.jsx'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['es2022'],
  outfile: check ? resolve(desktopDir, '.cache/plugin.js') : outfile,
  external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
  jsx: 'automatic',
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  loader: { '.woff2': 'dataurl' },
  logLevel: 'info',
  banner: { js: banner },
}

mkdirSync(dirname(options.outfile), { recursive: true })
await esbuild.build(options)


function sha(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex')
}

const ALLOWED_IMPORTS = new Set([
  '@hermes/plugin-sdk',
  'react',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
])

function hostImports(source) {
  const found = []
  const re = /(?:^|[^\w.$])import(?:\s*\*\s*as\s+[\w$]+|\s*\{[^}]*\}|\s+[\w$]+(?:\s*,\s*\{[^}]*\})?)?\s*from\s*["']([^"']+)["']/g
  let m
  while ((m = re.exec(source))) found.push(m[1])
  return found
}

function assertHostImports(path) {
  const text = readFileSync(path, 'utf8')
  const imports = hostImports(text)
  const unique = [...new Set(imports)]
  const bad = unique.filter((s) => !ALLOWED_IMPORTS.has(s))
  if (bad.length) {
    console.error('bundle imports non-host specifiers:', bad.join(', '))
    process.exit(1)
  }
  if (!unique.includes('@hermes/plugin-sdk')) {
    console.error('bundle is missing import of @hermes/plugin-sdk')
    process.exit(1)
  }
  if (!unique.includes('react') && !unique.includes('react/jsx-runtime')) {
    console.error('bundle is missing a host React import')
    process.exit(1)
  }
  return unique
}

function assertRequireShim(path) {
  const text = readFileSync(path, 'utf8')
  if (!text.includes('var require = function __uirizzRequire')) {
    console.error('bundle is missing the ESM require shim for host React')
    process.exit(1)
  }
}

if (check) {
  const expected = sha(outfile)
  const actual = sha(options.outfile)
  if (expected !== actual) {
    console.error('desktop/plugin.js is stale. Run npm run build in desktop/ and commit the bundle.')
    process.exit(1)
  }
  assertHostImports(outfile)
  assertRequireShim(outfile)
  console.log('desktop/plugin.js is up to date')
} else {
  const unique = assertHostImports(outfile)
  assertRequireShim(outfile)
  console.log('wrote', outfile, 'bytes', readFileSync(outfile).length, 'sha256', sha(outfile).slice(0, 16), 'imports', unique.join(','))
}
